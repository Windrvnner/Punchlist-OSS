// What must never appear in commits, pull requests, issues, comments, docs, or code: AI-tool attribution lines,
// footers, and links to AI chat sessions. The repository check (check-attribution.mjs) and other checks use this
// list. Patterns work as JavaScript regular expressions and as `git grep -E` (extended) patterns, matched ignoring
// case. Some are written in pieces so this file does not match its own check.
const NAMES = 'Cla' + 'ude|Anthropic|ChatGPT|Copilot|Cod' + 'ex|Gemini|Cursor|Sonnet|Opus|Haiku';
const END = '([/?#)>\" ]|$)'; // what may follow a link's path, so a longer host or path is not mistaken for it
// The one allowed footer: a generic product link, not a link to a session.
// It is allowed only as the last lines of a text, so any other claude.ai link still counts. Written in pieces so
// this file does not match its own check.
const SESSION_FOOTER = new RegExp(
  '\\n\\n---\\n_Generated by \\[' + 'Cla' + 'ude Code\\]\\(https://' + 'cla' + 'ude\\.ai/code\\)_\\n?$',
);

/** The text without the allowed footer at its end, when it ends with one. */
export function withoutSessionFooter(text) {
  return text.replace(SESSION_FOOTER, '');
}
export const AI_ATTRIBUTION_PATTERNS = [
  { name: 'a link to an AI chat or session site', pattern: '(^|[^A-Za-z0-9.-])(www\\.)?' + 'claude\\.ai/' },
  {
    name: 'an AI chat share link',
    pattern: '(chatgpt\\.com|chat\\.openai\\.com)/(share|c)/|gemini\\.google\\.com/(share|app)/',
  },
  { name: 'an AI tool link in a footer', pattern: 'claude\\.com/(' + 'claude-code|code)' + END },
  { name: 'a hidden attribution comment', pattern: 'claude-projects-' + 'attribution' },
  { name: 'a "generated with" footer', pattern: '(Generated|Made) (with|by) +[^A-Za-z]{0,3}' + 'Claude Code' },
  { name: 'a "requested by" header', pattern: '^[ >_]*Requested by +\\*\\*' },
  { name: 'an AI co-author trailer', pattern: '^[ >]*Co-Authored-By *:[^<]*\\b(' + NAMES + ')\\b' },
  { name: 'an AI session trailer', pattern: '^[ >]*(' + 'Cla' + 'ude|Cod' + 'ex|AI)-Session *:' },
];

/** The kinds of AI attribution a text holds, by name; empty when it holds none. */
export function aiAttributionIn(text) {
  const body = withoutSessionFooter(text);
  return AI_ATTRIBUTION_PATTERNS.filter(({ pattern }) => new RegExp(pattern, 'im').test(body)).map(({ name }) => name);
}
