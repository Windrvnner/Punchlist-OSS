/** What `git grep -E` says about a text, line by line, for every pattern together. */
function grepMatches(text: string): boolean {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-grep-'));
  fs.writeFileSync(path.join(dir, 'f.txt'), `${text}\n`);
  const patterns = AI_ATTRIBUTION_PATTERNS.flatMap(({ pattern }) => ['-e', pattern]);
  execFileSync('git', ['init', '-q'], { cwd: dir });
  return spawnSync('git', ['grep', '--no-index', '-i', '-E', '-q', ...patterns, 'f.txt'], { cwd: dir }).status === 0;
}

describe('the attribution patterns', () => {
  it.each(refused)('refuse %s, in JavaScript and in git grep', (text) => {
    expect(aiAttributionIn(text)).not.toEqual([]);
    expect(aiAttributionIn(text.replace(/\n/g, '\r\n'))).not.toEqual([]);
    expect(grepMatches(text)).toBe(true);
  });

  it.each(allowed)('pass %s, in JavaScript and in git grep', (text) => {
    expect(aiAttributionIn(text)).toEqual([]);
    expect(aiAttributionIn(`Title\n\n${text}\nNext line\n`)).toEqual([]);
    expect(aiAttributionIn(`Title\r\n\r\n${text}\r\nNext line\r\n`)).toEqual([]);
    expect(grepMatches(text)).toBe(false);
  });
});
