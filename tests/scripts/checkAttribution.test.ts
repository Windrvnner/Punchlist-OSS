// @vitest-environment node
// The attribution check: tracked files and the branch's commit messages must hold no AI-tool attribution, footer,
// or link to an AI chat session, no decision credited to a person, and no email address other than an example or
// no-reply one. The refused texts are built at run time, so this file itself holds none of them.
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

const script = path.resolve('scripts/check-attribution.mjs');
const refused = {
  link: ['https://claude', '.ai/code/session_01'].join(''),
  header: ['_Requested by', ' **Someone** · project thread_'].join(''),
  hidden: ['<!-- claude-projects', '-attribution: {} -->'].join(''),
  trailer: ['Co-Authored-By: Claude', ' <noreply@example.com>'].join(''),
  session: ['Claude-Sess', 'ion: x'].join(''),
  credit: ['Decision: newest first, as the ', 'owner asked (Jane Doe, Nov 18).'].join(''),
  email: ['Write to jane.doe', '@', 'firm.test about it.'].join(''),
};

const footer = ['Generated with [Claude', ' Code](https://claude.com/', 'claude-code)'].join('');
const productFooter = ['_Generated by [Claude', ' Code](https://claude', '.ai/code)_'].join('');

function repo() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'attribution-'));
  const git = (...args: string[]) => execFileSync('git', args, { cwd: dir });
  git('init', '-q', '-b', 'main');
  git('config', 'user.email', 't@example.com');
  git('config', 'user.name', 't');
  const commit = (message: string) => git('commit', '-q', '--allow-empty', '-m', message);
  const track = (file: string, text: string) => {
    fs.writeFileSync(path.join(dir, file), text);
    git('add', file);
  };
  const check = () => spawnSync('node', [script], { cwd: dir, encoding: 'utf8' });
  return { commit, track, check, git };
}

describe('the attribution check', () => {
  it("passes clean files, vendor documentation links, and a coding tool's plain footer (#729)", () => {
    const r = repo();
    r.track('a.md', 'See https://platform.claude.com/docs/en/api/overview. Sample generated with a script.\n');
    r.track('b.md', `${productFooter}\nNext line\n`);
    r.track('c.md', `Rules quote "the ${'owner'} wants". Mail a@example.com or 1+a@users.noreply.github.com.\n`);
    r.track('package-lock.json', `{ "deprecated": "contact i${'@'}firm.test" }\n`);
    r.commit(`Add a note\n\n${footer}\n${productFooter}\n`);
    expect(r.check().status).toBe(0);
  });

  it.each(Object.entries(refused))('refuses a tracked file that holds the %s', (_name, text) => {
    const r = repo();
    r.track('a.md', `Text\n\n${text}\n`);
    r.commit('Add a note');
    const out = r.check();
    expect(out.status).toBe(1);
    expect(out.stderr).toContain('a.md');
    expect(out.stderr).not.toContain(text);
  });

  it('refuses a commit message of the branch, and ignores older commits on main', () => {
    const r = repo();
    r.commit(`Old\n\n${refused.trailer}`);
    r.git('checkout', '-q', '-b', 'topic');
    r.commit('Clean change');
    expect(r.check().status).toBe(0);
    r.commit(`Bad change\n\n${refused.session}`);
    const out = r.check();
    expect(out.status).toBe(1);
    expect(out.stderr).toContain('commit');
  });

  it.each(['credit', 'email'] as const)('refuses a commit message of the branch that holds the %s', (name) => {
    const r = repo();
    r.commit('Old');
    r.git('checkout', '-q', '-b', 'topic');
    r.commit(`Change\n\n${refused[name]}`);
    const out = r.check();
    expect(out.status).toBe(1);
    expect(out.stderr).toContain('commit');
  });
});

describe('the attribution check on main and on a fresh history', () => {
  it('reads the latest commits when the branch adds none, as on main itself', () => {
    const r = repo();
    r.commit(`Bad change\n\n${refused.trailer}`);
    const out = r.check();
    expect(out.status).toBe(1);
    expect(out.stderr).toContain('commit');
  });
});
